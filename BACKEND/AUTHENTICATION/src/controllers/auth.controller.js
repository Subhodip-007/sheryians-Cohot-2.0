export const refreshTokenController = async(req,res)=>{
    try{
        const refreshToken = req.cookies.refreshToken;
        if(!refreshToken){
            return res.status(401).json({
                message:"RefreshToken not found",
                success:false
            })
        }
        const decoded = jwt.verify(refreshToken,config.JWT_SECRET);
        const refreshTokenHashed =  crypto.createHash("sha256").update(decoded).digest("hex")
        const session = await sessionModel.findOne({
                refreshTokenHash:refreshTokenHashed,
                revoked:false
        })
        if(!session){
            return res.status(401).json({
                message:"invalid tokeen",
                success:true
            })
        }
        const accessToken = jwt.sign({
            _id:decoded._id
        },config.JWT_SECRET,{
            expiresIn:"15m"
        })
        // for security we can generate new refresh token 
        const newRefreshToken = jwt.sign({
            _id:decoded._id
        },config.JWT_SECRET,{
            expiresIn:"7d"
        })
         const newrefreshTokenHashed =  crypto.createHash("sha256").update(newRefreshToken).digest("hex")
         session.refreshTokenHash = newrefreshTokenHashed
         await session.save()
        res.cookie("refreshToken",refreshToken),{
            httpOnly:true,
            secure:true,
            sameSite:"strict",
            maxAge :7*24*60 *60 * 1000 //7days
         }
        res.status(200).json({
            message:"accessToken refreshed successful",
            success:true
        })


    }catch(err){
        return res.status(500).json({
            message:err,
            success:false
        })
    }
}
