export const logoutController = async (req,res)=>{
    try{
        const refreshToken = req.cookies.refreshToken;
        if(!refreshToken){
             return res.status(401).json({
                message:"token not found",
                success:false
            })
        }
        const hashedRefToken = crypto.createHash("sha256").update(refreshToken).digest("hex");
        let isvalidRefToken = await sessionModel.findOne({
            refreshTokenHash:hashedRefToken,
            revoked:false
        })
        if(!isvalidRefToken){
            return res.status(401).json({
                message:"invalid token",
                success:false
            })
        }
        isvalidRefToken.revoked=true;
        res.clearCookie('refreshToken');
        await isvalidRefToken.save()


    }catch(err){
        return res.status(500).json({
            message:err,
            success:false
        })
    }
}
