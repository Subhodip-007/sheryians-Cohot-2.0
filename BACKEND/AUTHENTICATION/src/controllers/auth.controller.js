export const verifyOtpController = async (req, res) => {
    try {
        const { email, otp } = req.body;

        // 1. Basic validation
        if (!email || !otp) {
            return res.status(400).json({
                success: false,
                message: "Email and OTP are required"
            });
        }

        // 2. Hash the incoming OTP to match the database storage format
        const hashedOtp = crypto.createHash("sha256").update(otp).digest("hex");

        // 3. Search and destroy the token atomically if it matches
        // This ensures an OTP can only be used exactly ONCE (One-Time Password)
        const otpRecord = await OtpModel.findOneAndDelete({
            email: email.toLowerCase().trim(),
            otp: hashedOtp
        });

        // 4. If no record was found, it's either incorrect or expired (deleted by TTL)
        if (!otpRecord) {
            return res.status(400).json({
                success: false,
                message: "Invalid or expired OTP"
            });
        }

        // 5. Success! Proceed with your application logic
        // (e.g., updating user verification status in DB, generating JWTs, etc.)
        return res.status(200).json({
            success: true,
            message: "OTP verified successfully"
        });

    } catch (err) {
        return res.status(500).json({
            success: false,
            message: err.message || err
        });
    }
};
